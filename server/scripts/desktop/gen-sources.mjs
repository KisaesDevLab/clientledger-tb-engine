// Writes src/desktop/sources.generated.ts: static require() lists of every
// migration and seed, so a bundled desktop engine needs no migrations/ or
// seeds/ folder at runtime. Run before building (npm run desktop:gen).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const server = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const list = (dir) => fs.readdirSync(path.join(server, dir)).filter((f) => f.endsWith('.js')).sort();

const entries = (dir) =>
  list(dir).map((f) => `  ['${f}', () => require('../../${dir}/${f}')],`).join('\n');

const out = `// GENERATED by scripts/desktop/gen-sources.mjs. Do not edit.
/* eslint-disable @typescript-eslint/no-require-imports */

export type ModuleThunk = () => unknown;

export const MIGRATIONS: ReadonlyArray<readonly [string, ModuleThunk]> = [
${entries('migrations')}
];

export const SEEDS: ReadonlyArray<readonly [string, ModuleThunk]> = [
${entries('seeds')}
];
`;
fs.writeFileSync(path.join(server, 'src/desktop/sources.generated.ts'), out);
console.log(`[desktop:gen] ${list('migrations').length} migrations, ${list('seeds').length} seeds`);
